/**
 * Splits the classmates' English messages into a selection set (for choosing models) and a held-out set (reporting
 * only: never used for tuning or selection): `npx tsx scripts/split-eval-set.ts <input.json> [--held-out 0.5]`.
 *
 * Input: a JSON array of { text, command, alsoOk? } (command = the chat command the message should run, labelled
 * by someone other than whoever tunes the rules). Each message's side is fixed by a salted hash of its normalised
 * text, so re-running gives the same split, exact duplicates can't sit on both sides, and adding messages later
 * doesn't move the old ones. Writes tests/eval/chat-selection.json and tests/eval/chat-heldout-classmates.json.
 * English only (Urdu and Roman Urdu are deferred until after 10 Nov 2026).
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
/** Fixed salt: changing it reshuffles every row, so it never changes once the held-out set has been reported. */
export const SPLIT_SALT = "life-organizer-classmates-2026-10";
type Row = { text: string; command: string; alsoOk?: string[] };
const norm = (t: string) => t.trim().toLowerCase().replace(/\s+/g, " ");

/** 0..1 from the salted hash: below `heldOut` goes to the held-out set. */
export function side(text: string, heldOut = 0.5): "selection" | "heldout" {
  const h = createHash("sha256").update(`${SPLIT_SALT}|${norm(text)}`).digest();
  return h.readUInt32BE(0) / 0x100000000 < heldOut ? "heldout" : "selection";
}

export function split(rows: Row[], heldOut = 0.5): { selection: Row[]; heldout: Row[]; duplicates: number; unlabelled: number } {
  const seen = new Set<string>();
  const out = { selection: [] as Row[], heldout: [] as Row[], duplicates: 0, unlabelled: 0 };
  for (const r of rows) {
    if (!r.command?.trim()) {
      out.unlabelled += 1;
      continue;
    }
    const key = norm(r.text);
    if (!key || seen.has(key)) {
      out.duplicates += 1;
      continue;
    }
    seen.add(key);
    out[side(r.text, heldOut)].push({ text: r.text.trim(), command: r.command.trim(), ...(r.alsoOk?.length ? { alsoOk: r.alsoOk } : {}) });
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const input = process.argv[2];
  if (!input) throw new Error("usage: npx tsx scripts/split-eval-set.ts <input.json> [--held-out 0.5]");
  const i = process.argv.indexOf("--held-out");
  const heldOut = i > 0 ? Number(process.argv[i + 1]) : 0.5;
  const s = split(JSON.parse(readFileSync(input, "utf8")) as Row[], heldOut);
  const write = (file: string, rows: Row[], about: string) => writeFileSync(join(root, "tests/eval", file), `${JSON.stringify({ about, salt: SPLIT_SALT, heldOutShare: heldOut, rows: rows.map((r, n) => ({ id: `${file.startsWith("chat-selection") ? "s" : "h"}${String(n + 1).padStart(3, "0")}`, lang: "en", ...r })) }, null, 1)}\n`);
  write("chat-selection.json", s.selection, "Classmates' English messages, selection half: used to choose models (scripts/bench-providers.ts --set selection). Generated by scripts/split-eval-set.ts.");
  write("chat-heldout-classmates.json", s.heldout, "Classmates' English messages, held-out half: reporting only. Never used for tuning, few-shot banks or model selection; --set heldout is reported, never ranked.");
  console.log(`selection ${s.selection.length}, held-out ${s.heldout.length}, duplicates dropped ${s.duplicates}, unlabelled skipped ${s.unlabelled}`);
}
