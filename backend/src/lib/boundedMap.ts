/** Map.set that keeps at most `max` entries, dropping the oldest. Setting a key again makes it the newest. */
export function setBounded<K, V>(map: Map<K, V>, key: K, value: V, max: number): void {
  map.delete(key);
  map.set(key, value);
  while (map.size > max) map.delete(map.keys().next().value as K);
}
