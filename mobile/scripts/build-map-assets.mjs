/**
 * Inlines Leaflet (JS + CSS) from node_modules into src/components/map/leaflet.generated.ts, so the map page
 * needs no CDN at runtime. Run after upgrading leaflet: `npm run map:assets`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "node_modules/leaflet/dist");
const { version } = JSON.parse(readFileSync(join(root, "node_modules/leaflet/package.json"), "utf8"));
const license = readFileSync(join(root, "node_modules/leaflet/LICENSE"), "utf8").trim();
// "</script" inside the inlined code would end the page's <script> tag early.
const js = readFileSync(join(dist, "leaflet.js"), "utf8").replace(/<\/script/gi, "<\\/script");
const css = readFileSync(join(dist, "leaflet.css"), "utf8");

const out = `/* eslint-disable */
// Generated by scripts/build-map-assets.mjs from leaflet@${version}. Do not edit; run \`npm run map:assets\`.
/*
${license}
*/
export const LEAFLET_VERSION = ${JSON.stringify(version)};
export const LEAFLET_CSS = ${JSON.stringify(css)};
export const LEAFLET_JS = ${JSON.stringify(js)};
`;
writeFileSync(join(root, "src/components/map/leaflet.generated.ts"), out);
console.log(`Wrote leaflet ${version} (${Math.round(out.length / 1024)} KB).`);
